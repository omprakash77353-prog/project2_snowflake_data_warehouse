-- Project 2: Snowflake Data Warehouse with Streams and Tasks
-- Run statements in order. Replace COMPUTE_WH and role/grants as needed.

CREATE DATABASE IF NOT EXISTS DE_PROJECT;
CREATE SCHEMA IF NOT EXISTS DE_PROJECT.STAGING;
CREATE SCHEMA IF NOT EXISTS DE_PROJECT.ANALYTICS;

CREATE TABLE IF NOT EXISTS DE_PROJECT.STAGING.STG_CUSTOMERS (
    CUSTOMER_ID NUMBER(38,0),
    CUSTOMER_NAME STRING,
    EMAIL STRING,
    UPDATED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS DE_PROJECT.ANALYTICS.DIM_CUSTOMERS (
    CUSTOMER_ID NUMBER(38,0),
    CUSTOMER_NAME STRING,
    EMAIL STRING,
    UPDATED_AT TIMESTAMP_NTZ
);

