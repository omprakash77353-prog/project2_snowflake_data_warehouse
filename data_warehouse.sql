-- Run the MERGE statement above again to consume new stream changes.
-- Note: A stream is consumed by committed DML that reads it. Avoid querying it
-- for debugging before the MERGE, as this can advance the stream offset only
-- when a transaction commits changes that consume it.

-- Optional scheduled task. Requires a warehouse and suitable privileges.
CREATE TASK IF NOT EXISTS DE_PROJECT.STAGING.LOAD_CUSTOMERS_TASK
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '5 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('DE_PROJECT.STAGING.CUSTOMER_STREAM')
AS
MERGE INTO DE_PROJECT.ANALYTICS.DIM_CUSTOMERS T
USING (
    SELECT CUSTOMER_ID, CUSTOMER_NAME, EMAIL, UPDATED_AT
    FROM DE_PROJECT.STAGING.CUSTOMER_STREAM
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT DESC
    ) = 1
) S
ON T.CUSTOMER_ID = S.CUSTOMER_ID
WHEN MATCHED AND S.UPDATED_AT >= T.UPDATED_AT THEN UPDATE SET
    T.CUSTOMER_NAME = S.CUSTOMER_NAME,
    T.EMAIL = S.EMAIL,
    T.UPDATED_AT = S.UPDATED_AT
WHEN NOT MATCHED THEN INSERT
    (CUSTOMER_ID, CUSTOMER_NAME, EMAIL, UPDATED_AT)
    VALUES (S.CUSTOMER_ID, S.CUSTOMER_NAME, S.EMAIL, S.UPDATED_AT);

