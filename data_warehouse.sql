-- Stream captures inserts/updates/deletes after it is created.
CREATE STREAM IF NOT EXISTS DE_PROJECT.STAGING.CUSTOMER_STREAM
    ON TABLE DE_PROJECT.STAGING.STG_CUSTOMERS;

-- Initial load / incremental upsert from stream.
MERGE INTO DE_PROJECT.ANALYTICS.DIM_CUSTOMERS T
USING (
    SELECT CUSTOMER_ID, CUSTOMER_NAME, EMAIL, UPDATED_AT
    FROM DE_PROJECT.STAGING.CUSTOMER_STREAM
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT DESC
    ) = 1
) S
ON T.CUSTOMER_ID = S.CUSTOMER_ID
WHEN MATCHED AND S.UPDATED_AT >= T.UPDATED_AT THEN UPDATE SET
    T.CUSTOMER_NAME = S.CUSTOMER_NAME,
    T.EMAIL = S.EMAIL,
    T.UPDATED_AT = S.UPDATED_AT
WHEN NOT MATCHED THEN INSERT
    (CUSTOMER_ID, CUSTOMER_NAME, EMAIL, UPDATED_AT)
    VALUES (S.CUSTOMER_ID, S.CUSTOMER_NAME, S.EMAIL, S.UPDATED_AT);

-- Verify current warehouse table.
